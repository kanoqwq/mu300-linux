#!/usr/bin/env python3
"""Headers and link libraries for the C programs of the device that use ubus and uci (libubox, libubus, libuci).

The sources are the exact versions of the image's libraries (pinned in release/openwrt-sources.json, downloaded by
tools/fetch_openwrt_packages.py into build/openwrt-sources).  The headers are taken from them, and the three libraries are compiled from
them with the image's sonames, for linking only: OpenWrt's own libraries have no section headers (sstrip), which the linker needs.  At run
time the programs use the libraries of the image (same sources, so the same interface), linked dynamically like every OpenWrt program
(musl, /lib/ld-musl-aarch64.so.1).

usage: ubus_sysroot.py <out-dir>    (creates <out-dir>/include and <out-dir>/lib; an existing directory is rebuilt)"""
import hashlib
import io
import json
import shutil
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

from build_native_panel import cached_zig

REPO =Path(__file__).resolve().parents[1]
PINS = REPO / 'release' / 'openwrt-sources.json'
SRC = REPO / 'build' / 'openwrt-sources'
# library: (source archive prefix, C files, soname of the image's library, libraries it links, defines of its CMake build)
LIBS = {
    'ubox': ('libubox', ['avl.c', 'avl-cmp.c', 'blob.c', 'blobmsg.c', 'uloop.c', 'usock.c', 'ustream.c', 'ustream-fd.c', 'vlist.c', 'utils.c',
                         'safe_list.c', 'runqueue.c', 'md5.c', 'kvlist.c', 'ulog.c', 'base64.c', 'udebug.c', 'udebug-remote.c'],
             'libubox.so.20260213', [], []),
    'ubus': ('ubus', ['libubus.c', 'libubus-io.c', 'libubus-obj.c', 'libubus-sub.c', 'libubus-req.c', 'libubus-acl.c'],
             'libubus.so.20251202', ['ubox'], ['-DUBUS_UNIX_SOCKET="/var/run/ubus/ubus.sock"', '-DUBUS_MAX_MSGLEN=1048576']),
    'uci': ('uci', ['libuci.c', 'file.c', 'util.c', 'delta.c', 'parse.c', 'blob.c'], 'libuci.so.20250120', ['ubox'], []),
}


def zig():
    return str(cached_zig())


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    out = Path(sys.argv[1]).resolve()
    shutil.rmtree(out, ignore_errors=True)
    inc, lib = out / 'include', out / 'lib'
    (inc / 'libubox').mkdir(parents=True)
    lib.mkdir()
    pins = json.loads(PINS.read_text(encoding='utf-8'))['sources']
    work = Path(tempfile.mkdtemp(prefix='u30pro-ubus-'))
    try:
        trees = {}
        for name, pin in pins.items():
            data = (SRC / name).read_bytes()
            if hashlib.sha256(data).hexdigest() != pin['sha256']:
                raise SystemExit(f'{name}: SHA256 does not match {PINS.name}')
            with tarfile.open(fileobj=io.BytesIO(data), mode='r:gz') as tf:
                top = tf.getmembers()[0].name.split('/')[0]
                # the sources sit at the top of the tree (test corpora below it have names Windows cannot store)
                tf.extractall(work, members=[m for m in tf.getmembers() if m.isfile() and m.name.count('/') == 1], filter='data')
            trees[name.split('-')[0]] = work / top
            for h in sorted((work / top).glob('*.h')):
                shutil.copy(h, (inc / 'libubox') if pin['headers'] == 'libubox' else inc)
        # generated by the uci build (cmake)
        (inc / 'uci_config.h').write_text('#define UCI_PLUGIN_SUPPORT 1\n', encoding='utf-8')
        for name, (tree, sources, soname, deps, defines) in LIBS.items():
            src = trees[tree]
            cmd = [zig(), 'cc', '-target', 'aarch64-linux-musl', '-shared', '-fPIC', '-O2', '-std=gnu99', '-D_GNU_SOURCE', '-w', *defines,
                   '-I', str(inc), '-Wl,-soname,' + soname, '-o', str(lib / ('lib%s.so' % name)),
                   *[str(src / s) for s in sources], '-L', str(lib), *['-l' + d for d in deps]]
            r = subprocess.run(cmd, capture_output=True, text=True, timeout=300)
            if r.returncode:
                raise SystemExit(f'lib{name}: build failed\n{r.stdout}{r.stderr}')
    finally:
        shutil.rmtree(work, ignore_errors=True)
    print(out)


if __name__ == '__main__':
    main()
