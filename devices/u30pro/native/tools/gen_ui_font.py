#!/usr/bin/env python3
"""Bake the glyph tables of the on-device screen UI (tools/u30pro_ui.c) into tools/ui/font.h.

usage: gen_ui_font.py [--font NotoSansSC-VF.ttf] [--out tools/ui/font.h]

The UI has no font engine on the device: every size it uses is rendered here with Pillow into 4-bit alpha bitmaps.
Every non-ASCII character that appears in tools/u30pro_ui.c is added to all UI sizes automatically, and the 12/14/16 px
body sizes additionally carry GB2312 level 1 (3755 common hanzi) so that SMS text, operator names and host names
from the network render without a font file on the router.  The default font is Noto Sans SC (SIL OFL 1.1)."""
import argparse
import os
import re
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent
# the font that ships with Windows 11; on Linux a copy of that same file (SHA256 76314658...) in .cache/fonts
DEFAULT_FONT = Path('C:/Windows/Fonts/NotoSansSC-VF.ttf') if os.name == 'nt' else ROOT.parent / '.cache' / 'fonts' / 'NotoSansSC-VF.ttf'

# (name, pixel size, weight, charset kind)
FONTS = [
    ('F12', 12, 500, 'body'),
    ('F14', 14, 500, 'body'),
    ('F16', 16, 450, 'body'),
    ('B22', 22, 700, 'ui'),
    ('B34', 34, 700, 'ui'),
    ('B44', 44, 700, 'digits'),
    ('B56', 56, 700, 'digits'),
]
PUNCT = '，。！？：；、“”‘’（）【】《》…—·￥％＋－＝～　'
DIGITS = '0123456789:.-+% /°'


def gb2312_level1():
    out = []
    for row in range(0xB0, 0xD8):
        for col in range(0xA1, 0xFF):
            try:
                out.append(bytes([row, col]).decode('gb2312'))
            except UnicodeDecodeError:
                pass
    return out


def ui_chars():
    chars = set()
    for name in ('u30pro_ui.c',):
        p = ROOT / name
        if p.exists():
            chars.update(c for c in p.read_text(encoding='utf-8') if ord(c) > 0x7F)
    for p in sorted((ROOT / 'ui').glob('*.h')):
        if p.name != 'font.h':
            chars.update(c for c in p.read_text(encoding='utf-8') if ord(c) > 0x7F)
    chars.update('□°·→←↑↓×…—')
    return chars


def render(font, ch):
    l, t, r, b = font.getbbox(ch, anchor='ls')
    w, h = max(r - l, 0), max(b - t, 0)
    adv = int(round(font.getlength(ch)))
    if not w or not h:
        return {'w': 0, 'h': 0, 'bx': 0, 'by': 0, 'adv': adv, 'bits': b''}
    img = Image.new('L', (w, h), 0)
    ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor='ls')
    px = img.tobytes()
    nib = [(v * 15 + 127) // 255 for v in px]
    if len(nib) % 2:
        nib.append(0)
    bits = bytes((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
    return {'w': w, 'h': h, 'bx': l, 'by': t, 'adv': adv, 'bits': bits}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--font', type=Path, default=DEFAULT_FONT)
    ap.add_argument('--out', type=Path, default=ROOT / 'ui' / 'font.h')
    args = ap.parse_args()
    if not args.font.exists():
        sys.exit('font not found: ' + str(args.font))

    ascii_set = [chr(c) for c in range(0x20, 0x7F)]
    extra = sorted(ui_chars())
    blob = bytearray()
    tables = []
    for name, size, weight, kind in FONTS:
        font = ImageFont.truetype(str(args.font), size, layout_engine=ImageFont.Layout.BASIC)
        try:
            font.set_variation_by_axes([weight])
        except Exception as exc:  # static font: weight fixed
            print('no variation axes:', exc, file=sys.stderr)
        if kind == 'digits':
            chars = list(DIGITS)
        elif kind == 'body':
            chars = ascii_set + extra + list(PUNCT) + gb2312_level1()
        else:
            chars = ascii_set + extra
        seen = sorted(set(chars), key=ord)
        rows = []
        for ch in seen:
            g = render(font, ch)
            if ch != ' ' and not g['w'] and ord(ch) > 0x20:
                continue
            off = len(blob)
            blob.extend(g['bits'])
            rows.append((ord(ch), off, g))
        asc, desc = font.getmetrics()
        tables.append((name, size, rows, asc, asc + desc))
        print('%s %dpx w%d: %d glyphs' % (name, size, weight, len(rows)))

    lines = ['/* generated by tools/gen_ui_font.py from Noto Sans SC (SIL OFL 1.1); do not edit */',
             'typedef struct { uint32_t cp, off; uint8_t w, h; int8_t bx, by; uint8_t adv, pad; } UiGlyph;',
             'typedef struct { const UiGlyph *g; unsigned n; int ascent, line, size; } UiFont;',
             'static const uint8_t ui_font_bits[%d] = {' % max(len(blob), 1)]
    hexes = ['0x%02x' % b for b in blob] or ['0x00']
    for i in range(0, len(hexes), 24):
        lines.append(','.join(hexes[i:i + 24]) + (',' if i + 24 < len(hexes) else ''))
    lines.append('};')
    for name, size, rows, asc, line in tables:
        lines.append('static const UiGlyph ui_glyphs_%s[] = {' % name)
        for cp, off, g in rows:
            lines.append('{0x%x,%d,%d,%d,%d,%d,%d,0},' % (cp, off, g['w'], g['h'], g['bx'], g['by'], g['adv']))
        lines.append('};')
        lines.append('static const UiFont ui_font_%s = { ui_glyphs_%s, %d, %d, %d, %d };' % (name, name, len(rows), asc, line, size))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(('\n'.join(lines) + '\n').encode('utf-8'))
    print('wrote', args.out, len(blob), 'bytes of bitmaps')


if __name__ == '__main__':
    main()
