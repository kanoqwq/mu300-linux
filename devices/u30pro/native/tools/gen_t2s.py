#!/usr/bin/env python3
"""Traditional -> simplified fallback of the screen font (tools/ui/t2s.h).

The screen font carries the GB 2312 characters (simplified Chinese); text in traditional characters (Hong Kong and Taiwan server names,
network names, messages) would show boxes.  For every character with a kSimplifiedVariant in the Unicode Unihan database whose simplified
form is in the font and that is not in the font itself, t2s.h lists the pair; the UI draws the simplified glyph instead (gfx.h gx_glyph).

usage: python3 tools/gen_t2s.py Unihan_Variants.txt > tools/ui/t2s.h
Source used: https://www.unicode.org/Public/16.0.0/ucd/Unihan.zip
(sha256 b8f000df69de7828d21326a2ffea462b04bc7560022989f7cc704f10521ef3e0)."""
import re
import sys
from pathlib import Path

FONT = Path(__file__).resolve().parent / 'ui' / 'font.h'


def font_cps(name):
    text = FONT.read_text(encoding='utf-8')
    body = text[text.index('ui_glyphs_%s[' % name):]
    body = body[:body.index('};')]
    return {int(m.group(1), 16) for m in re.finditer(r'\{0x([0-9a-fA-F]+),', body)}


def main():
    have = font_cps('F16') & font_cps('F14') & font_cps('F12')
    pairs = {}
    for line in Path(sys.argv[1]).read_text(encoding='utf-8').splitlines():
        f = line.split('\t')
        if len(f) < 3 or f[1] != 'kSimplifiedVariant':
            continue
        src = int(f[0][2:], 16)
        dst = int(f[2].split()[0][2:], 16)
        if src == dst or src > 0xFFFF or src in have or dst not in have:
            continue
        pairs.setdefault(src, dst)
    out = ['/* generated by tools/gen_t2s.py from Unihan 16.0.0 (kSimplifiedVariant); do not edit */',
           '/* traditional characters missing from the font -> their simplified form (in the font), sorted for a binary search */',
           'static const uint16_t ui_t2s[][2] = {']
    items = sorted(pairs.items())
    for i in range(0, len(items), 8):
        out.append('\t' + ' '.join('{0x%04x,0x%04x},' % p for p in items[i:i + 8]))
    out.append('};')
    print('\n'.join(out))
    print('%d pairs' % len(items), file=sys.stderr)


main()
